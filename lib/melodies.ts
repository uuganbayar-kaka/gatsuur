/** Нотны нийт урттай тэнцүү, бит бүрт давтагдах энгийн бас (хөгжмийн хайрцагны доод дуу). */
function bassFor(notes: Note[], pattern: number[], beat: number): Note[] {
  const total = notes.reduce((s, [, d]) => s + d, 0);
  const out: Note[] = [];
  for (let t = 0, i = 0; t < total; t += beat, i++) out.push([pattern[Math.floor(i / 2) % pattern.length], beat]);
  return out;
}

